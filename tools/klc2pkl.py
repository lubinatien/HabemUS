"""Convert an MSKLC .klc file into a Portable Keyboard Layout (PKL) layout.ini.

Usage: python tools/klc2pkl.py [HabemUS.klc] [pkl/layouts/habemus/layout.ini]

PKL reads layout.ini through the ANSI Win32 INI API, so the output is UTF-8
without a BOM. Each [layout] row and each [deadkeyN] entry must end with a
"<tab>; comment" field: PKL drops the last tab-separated field of a layout
row, and cuts dead key values at the first tab.
"""
import sys
from datetime import datetime
from pathlib import Path

# The Ctrl column only holds control characters (Esc, FS, GS...). Leaving it
# out lets PKL send Ctrl+<key> as a plain shortcut, which yields the same
# control characters in the programs that care about them.
SKIPPED_STATES = {"2"}


def char(code):
    return chr(int(code, 16))


def pkl_value(token, deadkeys):
    if token == "-1":
        return "--"
    if token.endswith("@"):
        return "dk%d" % deadkeys[char(token[:-1])]
    if len(token) == 1:  # MSKLC writes digits and letters literally
        return token
    c = char(token)
    if c == " ":
        return "={space}"
    return c


def describe(cols, deadkeys):
    """Human-readable summary of a row, e.g. "6 ^ ¼ dead^"."""
    names = list(deadkeys)
    words = []
    for v in cols:
        if v.startswith("dk"):
            words.append("dead" + names[int(v[2:]) - 1])
        elif v == "={space}":
            words.append("space")
        elif v.isspace():
            words.append("U+%04X" % ord(v))
        else:
            words.append(v)
    return " ".join(words)


def parse_klc(path):
    lines = path.read_text(encoding="utf-16").splitlines()
    info = {}
    states = []
    rows = []
    deadkeys = {}  # dead char -> [(base, result)]
    section = None
    current_dk = None
    for raw in lines:
        line, _, comment = raw.partition("//")
        fields = line.split()
        if not fields or line.lstrip().startswith(";"):
            continue
        head = fields[0]
        if head == "KBD":
            info["KBDNAME"] = fields[1]
            continue
        if head in ("COPYRIGHT", "COMPANY", "LOCALEID", "VERSION"):
            info[head] = line.split(None, 1)[1].strip().strip('"')
            continue
        if head in ("SHIFTSTATE", "LAYOUT", "KEYNAME", "KEYNAME_EXT", "KEYNAME_DEAD",
                    "DESCRIPTIONS", "LANGUAGENAMES", "ENDKBD"):
            section = head
            continue
        if head == "DEADKEY":
            section = head
            current_dk = char(fields[1])
            deadkeys[current_dk] = []
            continue
        if section == "SHIFTSTATE":
            states.append(head)
        elif section == "LAYOUT":
            rows.append((fields[0], fields[1], fields[2], fields[3:], comment.strip()))
        elif section == "DEADKEY":
            deadkeys[current_dk].append((char(fields[0]), char(fields[1])))
        elif section == "DESCRIPTIONS" and head == "0409":
            info["DESCRIPTION"] = line.split(None, 1)[1].strip()
    return info, states, rows, deadkeys


def build_ini(klc_path, info, states, rows, deadkeys):
    dk_index = {c: i + 1 for i, c in enumerate(deadkeys)}
    kept = [i for i, s in enumerate(states) if s not in SKIPPED_STATES]
    col_names = {"0": "0Norm", "1": "1Sh", "2": "2Ctrl", "6": "6AGr", "7": "7AGrSh"}

    out = [
        ";",
        "; Keyboard Layout definition for",
        "; Portable Keyboard Layout",
        "; https://github.com/Portable-Keyboard-Layout/Portable-Keyboard-Layout",
        ";",
        "; Generated by tools/klc2pkl.py - edit the .klc and regenerate instead",
        "; of editing this file by hand.",
        ";",
        "",
        "[informations]",
        "layoutname           = %s" % info.get("DESCRIPTION", info["KBDNAME"]),
        "layoutcode           = %s" % info["KBDNAME"],
        "localeid             = %s" % info["LOCALEID"],
        "",
        "copyright            = %s" % info.get("COPYRIGHT", ""),
        "company              = %s" % info.get("COMPANY", ""),
        "version              = %s" % info.get("VERSION", ""),
        "",
        "generated_at         = %s" % datetime.now().strftime("%a %b %d %H:%M:%S %Y"),
        "generated_from       = %s" % klc_path.name,
        "modified_after_generate = no",
        "",
        "",
        "[global]",
        "shiftstates = %s" % ":".join(states[i] for i in kept),
        "",
        "",
        "[layout]",
        ";scan = VK\tCapStat\t" + "\t".join(col_names[states[i]] for i in kept),
    ]
    for sc, vk, cap, values, _ in rows:
        cols = [pkl_value(values[i], dk_index) for i in kept]
        out.append("SC0%s = %s\t%s\t%s\t; %s" % (sc.lower(), vk, cap, "\t".join(cols), describe(cols, deadkeys)))

    for dead, pairs in deadkeys.items():
        out += ["", "", "[deadkey%d]" % dk_index[dead]]
        out.append("%-4d = %5d\t; %s" % (0, ord(dead), dead))
        seen = set()
        for base, result in pairs:
            if base in seen:  # MSKLC tolerates duplicates, the INI keeps the first one
                continue
            seen.add(base)
            label = "space" if base == " " else base
            out.append("%-4d = %5d\t; %s -> %s" % (ord(base), ord(result), label, result))
    return "\r\n".join(out) + "\r\n"


def main():
    root = Path(__file__).resolve().parent.parent
    klc = Path(sys.argv[1]) if len(sys.argv) > 1 else root / "HabemUS.klc"
    dest = Path(sys.argv[2]) if len(sys.argv) > 2 else root / "pkl" / "layouts" / "habemus" / "layout.ini"
    info, states, rows, deadkeys = parse_klc(klc)
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_bytes(build_ini(klc, info, states, rows, deadkeys).encode("utf-8"))
    print("Wrote %s (%d keys, %d dead keys)" % (dest, len(rows), len(deadkeys)))


if __name__ == "__main__":
    main()
